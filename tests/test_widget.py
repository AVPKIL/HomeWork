import pytest

from src.widget import mask_account_card, get_date


# Параметризованные тесты для карт
@pytest.mark.parametrize(
    "input_data, expected",
    [
        # Стандартные карты
        ("Maestro 1596837868705199", "Maestro 1596 83** **** 5199"),
        ("MasterCard 7158300734726758", "MasterCard 7158 30** **** 6758"),
        ("Visa Classic 6831982476737658", "Visa Classic 6831 98** **** 7658"),
        ("Visa Platinum 8990922113665229", "Visa Platinum 8990 92** **** 5229"),
        ("Visa Gold 5999414228426353", "Visa Gold 5999 41** **** 6353"),
        # Карты с разным форматированием
        (" Visa 1234567890123456 ", "Visa 1234 56** **** 3456"),
        # Граничные случаи
        ("Карта 0000000000000000", "Карта 0000 00** **** 0000"),
        ("Карта 9999999999999999", "Карта 9999 99** **** 9999"),
    ],
)

def test_card_masking(input_data: str, expected: str) -> None:
    """Тестирование маскирования номеров карт"""

    result = mask_account_card(input_data)
    assert result == expected


# Параметризованные тесты для счетов
@pytest.mark.parametrize(
    "input_data, expected",
    [
        # Стандартные счета
        ("12345678901234567890", "**7890"),
        ("00000000000000000000", "**0000"),
        # Счета с разным форматированием
        ("  12345678901234567890  ", "**7890"),
        ("    12345678901234567890", "**7890"),
        # Граничные случаи
        ("11111111111111111111", "**1111"),
    ],
)
def test_account_masking(input_data: str, expected: str) -> None:
    """Тестирование маскирования номеров счетов"""
    assert mask_account_card(input_data) == expected


# Тест для проверки регистронезависимости
def test_case_insensitivity() -> None:
    """Проверка что 'счет' в любом регистре обрабатывается как счет"""
    assert mask_account_card("сЧеТ 12345678901234567890") == "сЧеТ **7890"
    assert mask_account_card("СЧЕТ 12345678901234567890") == "СЧЕТ **7890"


# Тестирование правильности преобразования даты
@pytest.mark.parametrize(
    "input_date, expected",
    [
        # Стандартные форматы
        ("2023-04-15T12:30:45", "15.04.2023"),
        ("2020-02-29T00:00:00", "29.02.2020"),  # Високосный год
        ("1999-12-31T23:59:59", "31.12.1999"),
        # Граничные случаи дат
        ("0001-01-01T00:00:00", "01.01.0001"),  # Минимальная дата
        ("9999-12-31T23:59:59", "31.12.9999"),  # Максимальная дата
        # Разные варианты времени
        ("2023-04-15T00:00:00", "15.04.2023"),
        ("2023-04-15T23:59:59", "15.04.2023"),
        # Даты без времени (не по стандарту, но возможные)
        ("2023-04-15", "15.04.2023"),
    ],
)
def test_valid_date_formats(input_date: str, expected: str) -> None:
    """Тестирование правильности преобразования валидных дат"""
    assert get_date(input_date) == expected


def test_invalid_date_formats(invalid_dates: str) -> None:
    """Тестирование обработки некорректных форматов даты"""
    for invalid_date in invalid_dates:
        assert get_date(invalid_date) == "Некорректный формат даты"
